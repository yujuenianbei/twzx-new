#!/bin/bash

# 简单的乘法脚本

# 检查参数数量
if [ $# -ne 2 ]; then
    echo "用法: $0 <数字1> <数字2>"
    echo "示例: $0 5 3"
    exit 1
fi

# 检查参数是否为数字
if ! [[ $1 =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || ! [[ $2 =~ ^-?[0-9]+(\.[0-9]+)?$ ]]; then
    echo "错误: 请输入有效的数字"
    exit 1
fi

# 计算乘积
result=$(awk "BEGIN {print $1 * $2}")

# 输出结果
echo "$1 * $2 = $result"
